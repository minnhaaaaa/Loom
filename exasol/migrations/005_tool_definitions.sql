-- Tool structure is immutable per draft/revision and published separately from business data.
ALTER TABLE REQUESTS ADD COLUMN CUSTOM_VALUES_JSON VARCHAR(20000) DEFAULT '{}' NOT NULL;
CREATE TABLE TOOLS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  CURRENT_REVISION DECIMAL(18,0) NOT NULL,
  CONSTRAINT PK_TOOLS PRIMARY KEY (WORKSPACE_ID) ENABLE,
  CONSTRAINT FK_TOOL_WORKSPACE FOREIGN KEY (WORKSPACE_ID) REFERENCES WORKSPACES(ID) ENABLE
);
CREATE TABLE TOOL_DRAFTS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  ID VARCHAR(36) NOT NULL,
  BASE_REVISION DECIMAL(18,0) NOT NULL,
  SPEC_JSON VARCHAR(100000) NOT NULL,
  INSTRUCTIONS VARCHAR(4000),
  ASSUMPTIONS_JSON VARCHAR(20000) NOT NULL,
  UNSUPPORTED_JSON VARCHAR(20000) NOT NULL,
  CONTENT_HASH VARCHAR(64) NOT NULL,
  CREATED_BY VARCHAR(36) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_TOOL_DRAFTS PRIMARY KEY (WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_TOOL_DRAFT_CREATOR FOREIGN KEY (WORKSPACE_ID,CREATED_BY) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
CREATE TABLE TOOL_REVISIONS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  REVISION DECIMAL(18,0) NOT NULL,
  SPEC_JSON VARCHAR(100000) NOT NULL,
  SPEC_HASH VARCHAR(64) NOT NULL,
  DRAFT_ID VARCHAR(36),
  PUBLISHED_BY VARCHAR(36),
  PUBLISHED_AT TIMESTAMP,
  CONSTRAINT PK_TOOL_REVISIONS PRIMARY KEY (WORKSPACE_ID,REVISION) ENABLE,
  CONSTRAINT FK_TOOL_REVISION_DRAFT FOREIGN KEY (WORKSPACE_ID,DRAFT_ID) REFERENCES TOOL_DRAFTS(WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_TOOL_PUBLISHER FOREIGN KEY (WORKSPACE_ID,PUBLISHED_BY) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
CREATE TABLE TOOL_EVENTS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  ID VARCHAR(36) NOT NULL,
  ACTOR_ID VARCHAR(36) NOT NULL,
  COMMAND_ID VARCHAR(36) NOT NULL,
  ACTION_KIND VARCHAR(40) NOT NULL,
  REVISION DECIMAL(18,0) NOT NULL,
  DRAFT_ID VARCHAR(36),
  CREATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_TOOL_EVENTS PRIMARY KEY (WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_TOOL_EVENT_ACTOR FOREIGN KEY (WORKSPACE_ID,ACTOR_ID) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
-- Provider calls occur outside transactions. A durable command reservation prevents
-- concurrent duplicates and reconciles completed generation without another call.
CREATE TABLE TOOL_GENERATIONS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  COMMAND_ID VARCHAR(36) NOT NULL,
  ACTOR_ID VARCHAR(36) NOT NULL,
  PAYLOAD_HASH VARCHAR(64) NOT NULL,
  BASE_REVISION DECIMAL(18,0) NOT NULL,
  LIFECYCLE VARCHAR(20) NOT NULL,
  ATTEMPTS DECIMAL(18,0) NOT NULL,
  LEASE_ID VARCHAR(36) NOT NULL,
  LEASE_UNTIL TIMESTAMP NOT NULL,
  DRAFT_ID VARCHAR(36),
  INFERENCE_JSON VARCHAR(4000),
  ERROR_CODE VARCHAR(60),
  CREATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_TOOL_GENERATIONS PRIMARY KEY (WORKSPACE_ID,COMMAND_ID) ENABLE,
  CONSTRAINT FK_TOOL_GENERATION_ACTOR FOREIGN KEY (WORKSPACE_ID,ACTOR_ID) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE,
  CONSTRAINT FK_TOOL_GENERATION_DRAFT FOREIGN KEY (WORKSPACE_ID,DRAFT_ID) REFERENCES TOOL_DRAFTS(WORKSPACE_ID,ID) ENABLE
);
