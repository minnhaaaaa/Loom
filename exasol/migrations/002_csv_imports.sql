-- Immutable, actor-scoped review batches. Source text stays out of logs.
CREATE TABLE IMPORT_BATCHES (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  ID VARCHAR(36) NOT NULL,
  ACTOR_ID VARCHAR(36) NOT NULL,
  SOURCE_HASH VARCHAR(64) NOT NULL,
  PREVIEW_HASH VARCHAR(64) NOT NULL,
  PREVIEW_JSON VARCHAR(1000000) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  EXPIRES_AT TIMESTAMP NOT NULL,
  COMMITTED_IDS_JSON VARCHAR(10000),
  CONSTRAINT PK_IMPORT_BATCHES PRIMARY KEY (WORKSPACE_ID, ID) ENABLE,
  CONSTRAINT FK_IMPORT_ACTOR FOREIGN KEY (WORKSPACE_ID, ACTOR_ID) REFERENCES MEMBERSHIPS(WORKSPACE_ID, USER_ID) ENABLE
);
