import { randomUUID } from "node:crypto";
import { afterAll, beforeAll, expect, it } from "vitest";
import { isConfigured, readDatabase, writeDatabase } from "@loom/db-exasol";
import {
  createRequest,
  insertRequest,
  details,
  mutateRequest,
  snapshot,
} from "../../apps/web/server/desk";
import {
  commitImport,
  exportRequests,
  previewImport,
} from "../../apps/web/server/imports";
import type { Actor } from "@loom/contracts";
if (!isConfigured())
  throw new Error(
    "Live Exasol is required. Configure .env and run db:migrate before test:db. This suite never substitutes a fake database.",
  );
const workspaceA = randomUUID(),
  workspaceB = randomUUID();
const owner: Actor = { workspaceId: workspaceA, userId: randomUUID() };
const requester: Actor = { workspaceId: workspaceA, userId: randomUUID() };
const other: Actor = { workspaceId: workspaceB, userId: requester.userId };
const viewer: Actor = { workspaceId: workspaceA, userId: randomUUID() };
beforeAll(async () => {
  await writeDatabase(async (sql) => {
    for (const id of [workspaceA, workspaceB])
      await sql.execute("INSERT INTO WORKSPACES (ID,NAME) VALUES (?,?)", [
        id,
        "Loom integration fixture",
      ]);
    for (const [actor, name, role] of [
      [owner, "Fixture owner", "owner"],
      [requester, "Fixture requester", "requester"],
      [other, "Other requester", "requester"],
      [viewer, "Fixture viewer", "viewer"],
    ] as const)
      await sql.execute(
        "INSERT INTO MEMBERSHIPS (WORKSPACE_ID,USER_ID,NAME,ROLE,ACTIVE) VALUES (?,?,?,?,TRUE)",
        [actor.workspaceId, actor.userId, name, role],
      );
  });
});
afterAll(async () => {
  // Only UUIDs generated by this invocation are deleted. Never reset user data.
  await writeDatabase(async (sql) => {
    for (const table of [
      "IMPORT_BATCHES",
      "COMMENTS",
      "REQUEST_EVENTS",
      "AUDIT_EVENTS",
      "OUTBOX_EVENTS",
      "COMMAND_RECEIPTS",
      "REQUESTS",
      "MEMBERSHIPS",
      "WORKSPACES",
    ]) {
      for (const id of [workspaceA, workspaceB])
        await sql.execute(
          `DELETE FROM ${table} WHERE ${table === "WORKSPACES" ? "ID" : "WORKSPACE_ID"} = ?`,
          [id],
        );
    }
  });
});
it("persists commands atomically, isolates readers, and rejects stale/replayed conflicts", async () => {
  const commandId = randomUUID();
  const values = {
    title: "Live integration fixture",
    businessQuestion: "Verify the real SQL path.",
    reportingPeriod: "October 2026",
    dataset: "Synthetic events",
  };
  const record = await createRequest(requester, commandId, values);
  expect((await createRequest(requester, commandId, values)).id).toBe(
    record.id,
  );
  await expect(
    createRequest(requester, commandId, {
      ...values,
      title: "Changed payload",
    }),
  ).rejects.toThrow("different action");
  await createRequest(owner, randomUUID(), {
    ...values,
    title: "Owner-only request",
  });
  expect((await snapshot(requester)).requests).toHaveLength(1);
  expect((await snapshot(other)).requests).toHaveLength(0);
  await expect(details(other, record.id)).rejects.toThrow("not found");
  await expect(
    mutateRequest(viewer, record.id, randomUUID(), 1, {
      type: "set_status",
      status: "ready",
    }),
  ).rejects.toThrow("Viewers cannot");
  const comment = await mutateRequest(owner, record.id, randomUUID(), 1, {
    type: "add_comment",
    body: "Internal fixture note",
    visibility: "internal",
  });
  expect(comment.version).toBe(2);
  expect((await details(requester, record.id)).comments).toHaveLength(0);
  expect((await details(owner, record.id)).comments).toHaveLength(1);
  const results = await Promise.allSettled([
    mutateRequest(owner, record.id, randomUUID(), 2, {
      type: "set_status",
      status: "ready",
    }),
    mutateRequest(owner, record.id, randomUUID(), 2, {
      type: "set_priority",
      priority: "high",
    }),
  ]);
  expect(results.filter((r) => r.status === "fulfilled")).toHaveLength(1);
  expect(results.filter((r) => r.status === "rejected")).toHaveLength(1);
  await expect(
    mutateRequest(owner, record.id, randomUUID(), 1, {
      type: "set_priority",
      priority: "low",
    }),
  ).rejects.toThrow("changed");
  await readDatabase(async (sql) => {
    const [r] = await sql.query(
      "SELECT COUNT(*) AS N FROM COMMAND_RECEIPTS WHERE WORKSPACE_ID = ?",
      [workspaceA],
    );
    expect(Number(r.N)).toBe(4); // two creates, comment, one winning concurrent command
    const [events] = await sql.query(
      "SELECT COUNT(*) AS N FROM AUDIT_EVENTS WHERE WORKSPACE_ID = ?",
      [workspaceA],
    );
    expect(Number(events.N)).toBe(4);
  });
});
it("rolls back a partial write instead of leaving an unacknowledged record", async () => {
  const id = randomUUID();
  await expect(
    writeDatabase(async (sql) => {
      await sql.execute("INSERT INTO WORKSPACES (ID,NAME) VALUES (?,?)", [
        id,
        "Rollback fixture",
      ]);
      throw new Error("intentional rollback");
    }),
  ).rejects.toThrow("intentional rollback");
  const rows = await readDatabase((sql) =>
    sql.query("SELECT ID FROM WORKSPACES WHERE ID = ?", [id]),
  );
  expect(rows).toEqual([]);
});

it("reviews CSV before an atomic, replayable import and pages/searches/exports scoped records", async () => {
  const mapping = {
    title: 0,
    businessQuestion: 1,
    reportingPeriod: 2,
    dataset: 3,
  };
  const text =
    "title,question,period,dataset\n" +
    Array.from({ length: 26 }, (_, i) => `CSV fixture ${i},Why ${i}?,,`).join(
      "\n",
    );
  await expect(previewImport(requester, text, mapping)).rejects.toThrow(
    "owner or operator",
  );
  const invalid = await previewImport(
    owner,
    "title,question,period,dataset\nMissing question,,,",
    mapping,
  );
  if (!("batchId" in invalid)) throw new Error("Expected stored preview");
  await expect(
    commitImport(owner, invalid.batchId, invalid.previewHash, randomUUID()),
  ).rejects.toThrow("Fix every row");
  const before = await snapshot(owner);
  const preview = await previewImport(owner, text, mapping);
  if (!("batchId" in preview)) throw new Error("Expected stored preview");
  expect((await snapshot(owner)).requests).toHaveLength(before.requests.length);
  await expect(
    commitImport(requester, preview.batchId, preview.previewHash, randomUUID()),
  ).rejects.toThrow("owner or operator");
  await expect(
    commitImport(owner, preview.batchId, "0".repeat(64), randomUUID()),
  ).rejects.toThrow("current preview");
  const commandId = randomUUID();
  const result = await commitImport(
    owner,
    preview.batchId,
    preview.previewHash,
    commandId,
  );
  expect(result.ids).toHaveLength(26);
  expect(
    await commitImport(owner, preview.batchId, preview.previewHash, commandId),
  ).toEqual(result);
  expect(
    await commitImport(
      owner,
      preview.batchId,
      preview.previewHash,
      randomUUID(),
    ),
  ).toEqual(result);
  const reopened = await previewImport(owner, text, mapping);
  expect("committedIds" in reopened && reopened.committedIds).toEqual(
    result.ids,
  );
  const first = await snapshot(owner, { search: "CSV fixture" });
  const second = await snapshot(owner, { search: "CSV fixture", page: 1 });
  expect(first.requests).toHaveLength(25);
  expect(first.page?.hasMore).toBe(true);
  expect(second.requests).toHaveLength(1);
  expect(second.page?.hasMore).toBe(false);
  expect(
    new Set([...first.requests, ...second.requests].map((r) => r.id)).size,
  ).toBe(26);
  expect(first.requests.every((r) => r.status === "needs_info")).toBe(true);
  expect(
    (await snapshot(requester, { search: "CSV fixture" })).requests,
  ).toHaveLength(0);
  expect(
    (await snapshot(owner, { search: "CSV fixture", status: "done" })).requests,
  ).toHaveLength(0);
  expect(
    (await snapshot(owner, { search: "%' OR 1=1 --" })).requests,
  ).toHaveLength(0);
  const exported = await exportRequests(owner, { search: "CSV fixture" });
  expect(exported.split("\r\n")).toHaveLength(28);
  expect(
    await exportRequests(requester, { search: "CSV fixture" }),
  ).not.toContain("CSV fixture");
  expect(await exportRequests(requester, {})).not.toContain('"priority"');
  await expect(snapshot(owner, { page: -1 })).rejects.toThrow();
  await readDatabase(async (sql) => {
    const [events] = await sql.query(
      "SELECT COUNT(*) AS N FROM AUDIT_EVENTS WHERE WORKSPACE_ID = ? AND ACTION_KIND = 'imported'",
      [workspaceA],
    );
    const [outbox] = await sql.query(
      "SELECT COUNT(*) AS N FROM OUTBOX_EVENTS WHERE WORKSPACE_ID = ?",
      [workspaceA],
    );
    expect(Number(events.N)).toBe(26);
    expect(Number(outbox.N)).toBe(30);
  });
});

it("rolls back earlier imported records and their history after a later SQL failure", async () => {
  const title = `Rollback import ${randomUUID()}`;
  await expect(
    writeDatabase(async (sql) => {
      const member = {
        userId: owner.userId,
        name: "Fixture owner",
        role: "owner" as const,
      };
      const values = {
        title,
        businessQuestion: "Verify atomic import rollback",
        reportingPeriod: "",
        dataset: "",
      };
      await insertRequest(
        sql,
        owner,
        member,
        randomUUID(),
        "fixture",
        values,
        true,
      );
      // Bypass intake validation only in this fixture to force a database constraint failure mid-batch.
      await insertRequest(
        sql,
        owner,
        member,
        randomUUID(),
        "fixture",
        { ...values, title: "" },
        true,
      );
    }),
  ).rejects.toThrow();
  expect((await snapshot(owner, { search: title })).requests).toHaveLength(0);
  await readDatabase(async (sql) => {
    const [events] = await sql.query(
      "SELECT COUNT(*) AS N FROM AUDIT_EVENTS WHERE WORKSPACE_ID = ? AND ACTION_KIND = 'imported'",
      [workspaceA],
    );
    expect(Number(events.N)).toBe(26);
  });
});
