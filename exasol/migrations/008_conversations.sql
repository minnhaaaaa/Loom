CREATE TABLE CONVERSATION_TURNS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  ID VARCHAR(36) NOT NULL,
  USER_ID VARCHAR(36) NOT NULL,
  COMMAND_ID VARCHAR(36) NOT NULL,
  PROMPT VARCHAR(4000) NOT NULL,
  VISIBILITY VARCHAR(20) NOT NULL,
  "STATE" VARCHAR(20) NOT NULL,
  PROVIDER VARCHAR(20) NOT NULL,
  VERSION DECIMAL(18,0) NOT NULL,
  CONTEXT_HASH VARCHAR(64) NOT NULL,
  CONTEXT_JSON VARCHAR(200000) NOT NULL,
  RESULT_JSON VARCHAR(180000),
  LEASE_UNTIL TIMESTAMP,
  CONNECTION_ID VARCHAR(36),
  CREATED_AT TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_CONVERSATION_TURNS PRIMARY KEY (WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_CONVERSATION_WORKSPACE FOREIGN KEY (WORKSPACE_ID) REFERENCES WORKSPACES(ID) ENABLE,
  CONSTRAINT FK_CONVERSATION_AUTHOR FOREIGN KEY (WORKSPACE_ID,USER_ID) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
