ALTER TABLE MEMBERSHIPS ADD COLUMN VERSION DECIMAL(18,0) DEFAULT 1 NOT NULL;
CREATE TABLE AUTH_USERS (
  ID VARCHAR(36) NOT NULL,
  NAME VARCHAR(100) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_AUTH_USERS PRIMARY KEY (ID) ENABLE
);
CREATE TABLE AUTH_IDENTITIES (
  EMAIL VARCHAR(254) NOT NULL,
  USER_ID VARCHAR(36) NOT NULL,
  PASSWORD_HASH VARCHAR(300) NOT NULL,
  CONSTRAINT PK_AUTH_IDENTITIES PRIMARY KEY (EMAIL) ENABLE,
  CONSTRAINT FK_AUTH_IDENTITY_USER FOREIGN KEY (USER_ID) REFERENCES AUTH_USERS(ID) ENABLE
);
CREATE TABLE AUTH_SESSIONS (
  TOKEN_HASH VARCHAR(64) NOT NULL,
  USER_ID VARCHAR(36) NOT NULL,
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  EXPIRES_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_AUTH_SESSIONS PRIMARY KEY (TOKEN_HASH) ENABLE,
  CONSTRAINT FK_AUTH_SESSION_USER FOREIGN KEY (USER_ID) REFERENCES AUTH_USERS(ID) ENABLE,
  CONSTRAINT FK_AUTH_SESSION_WORKSPACE FOREIGN KEY (WORKSPACE_ID) REFERENCES WORKSPACES(ID) ENABLE
);
CREATE TABLE ACCOUNT_COMMANDS (
  USER_ID VARCHAR(36) NOT NULL,
  COMMAND_ID VARCHAR(36) NOT NULL,
  PAYLOAD_HASH VARCHAR(64) NOT NULL,
  RESULT_JSON VARCHAR(20000) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_ACCOUNT_COMMANDS PRIMARY KEY (USER_ID,COMMAND_ID) ENABLE,
  CONSTRAINT FK_ACCOUNT_COMMAND_USER FOREIGN KEY (USER_ID) REFERENCES AUTH_USERS(ID) ENABLE
);
CREATE TABLE WORKSPACE_INVITATIONS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  ID VARCHAR(36) NOT NULL,
  TOKEN_HASH VARCHAR(64) NOT NULL,
  ROLE VARCHAR(20) NOT NULL,
  LIFECYCLE VARCHAR(20) NOT NULL,
  VERSION DECIMAL(18,0) NOT NULL,
  CREATED_BY VARCHAR(36) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  EXPIRES_AT TIMESTAMP NOT NULL,
  ACCEPTED_BY VARCHAR(36),
  CONSTRAINT PK_WORKSPACE_INVITATIONS PRIMARY KEY (WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_INVITATION_WORKSPACE FOREIGN KEY (WORKSPACE_ID) REFERENCES WORKSPACES(ID) ENABLE,
  CONSTRAINT FK_INVITATION_CREATOR FOREIGN KEY (WORKSPACE_ID,CREATED_BY) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
CREATE TABLE WORKSPACE_EVENTS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  ID VARCHAR(36) NOT NULL,
  ACTOR_ID VARCHAR(36) NOT NULL,
  ACTION_KIND VARCHAR(40) NOT NULL,
  SUBJECT_ID VARCHAR(36),
  VERSION DECIMAL(18,0) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_WORKSPACE_EVENTS PRIMARY KEY (WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_WORKSPACE_EVENT_WORKSPACE FOREIGN KEY (WORKSPACE_ID) REFERENCES WORKSPACES(ID) ENABLE
);
