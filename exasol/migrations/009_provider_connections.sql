CREATE TABLE PROVIDER_CONNECTIONS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  VERSION DECIMAL(18,0) NOT NULL,
  PROVIDER VARCHAR(20) NOT NULL,
  MODEL VARCHAR(150) NOT NULL,
  MAX_TOKENS DECIMAL(18,0) NOT NULL,
  ACTIVE BOOLEAN NOT NULL,
  CREDENTIAL VARCHAR(8000),
  TESTED_AT TIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL,
  UPDATED_BY VARCHAR(36) NOT NULL,
  CONSTRAINT PK_PROVIDER_CONNECTIONS PRIMARY KEY (WORKSPACE_ID) ENABLE,
  CONSTRAINT FK_PROVIDER_WORKSPACE FOREIGN KEY (WORKSPACE_ID) REFERENCES WORKSPACES(ID) ENABLE,
  CONSTRAINT FK_PROVIDER_OWNER FOREIGN KEY (WORKSPACE_ID,UPDATED_BY) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
CREATE TABLE PROVIDER_TEST_ATTEMPTS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  COMMAND_ID VARCHAR(36) NOT NULL,
  ACTOR_ID VARCHAR(36) NOT NULL,
  PAYLOAD_HASH VARCHAR(64) NOT NULL,
  LIFECYCLE VARCHAR(20) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_PROVIDER_TEST_ATTEMPTS PRIMARY KEY (WORKSPACE_ID,COMMAND_ID) ENABLE,
  CONSTRAINT FK_PROVIDER_TEST_WORKSPACE FOREIGN KEY (WORKSPACE_ID) REFERENCES WORKSPACES(ID) ENABLE
);
