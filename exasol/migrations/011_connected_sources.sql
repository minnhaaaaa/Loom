CREATE TABLE SOURCE_CONNECTIONS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  PROVIDER VARCHAR(20) NOT NULL,
  VERSION DECIMAL(18,0) NOT NULL,
  OWNER_ID VARCHAR(36) NOT NULL,
  ACCOUNT_ID VARCHAR(300) NOT NULL,
  DISPLAY_NAME VARCHAR(160) NOT NULL,
  CREDENTIAL VARCHAR(32000),
  ACTIVE BOOLEAN NOT NULL,
  CONSTRAINT PK_SOURCE_CONNECTIONS PRIMARY KEY (WORKSPACE_ID,PROVIDER) ENABLE,
  CONSTRAINT FK_SOURCE_CONNECTION_OWNER FOREIGN KEY (WORKSPACE_ID,OWNER_ID) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
CREATE TABLE SOURCE_SIGNINS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  OWNER_ID VARCHAR(36) NOT NULL,
  ID VARCHAR(36) NOT NULL,
  CREDENTIAL VARCHAR(16000) NOT NULL,
  EXPIRES_AT TIMESTAMP NOT NULL,
  NEXT_POLL_AT TIMESTAMP NOT NULL,
  POLL_SECONDS DECIMAL(10,0) NOT NULL,
  CONSTRAINT PK_SOURCE_SIGNINS PRIMARY KEY (WORKSPACE_ID,OWNER_ID) ENABLE
);
CREATE TABLE CONNECTED_SOURCES (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  ID VARCHAR(36) NOT NULL,
  PROVIDER VARCHAR(20) NOT NULL,
  SOURCE_KEY VARCHAR(64) NOT NULL,
  CONFIG_JSON VARCHAR(8000) NOT NULL,
  DISPLAY_NAME VARCHAR(160) NOT NULL,
  CONNECTION_VERSION DECIMAL(18,0) NOT NULL,
  VERSION DECIMAL(18,0) NOT NULL,
  ACTIVE BOOLEAN NOT NULL,
  CURSOR_JSON VARCHAR(16000),
  LAST_SYNC_AT TIMESTAMP,
  NEXT_SYNC_AT TIMESTAMP NOT NULL,
  LEASE_ID VARCHAR(36),
  LEASE_UNTIL TIMESTAMP,
  LAST_ERROR VARCHAR(500),
  SKIPPED_COUNT DECIMAL(18,0) NOT NULL,
  CONSTRAINT PK_CONNECTED_SOURCES PRIMARY KEY (WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_CONNECTED_WORKSPACE FOREIGN KEY (WORKSPACE_ID) REFERENCES WORKSPACES(ID) ENABLE
);
CREATE TABLE SOURCE_ITEMS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  SOURCE_ID VARCHAR(36) NOT NULL,
  EXTERNAL_ID VARCHAR(300) NOT NULL,
  CONTENT_HASH VARCHAR(64) NOT NULL,
  RESOURCE_ID VARCHAR(36),
  RESOURCE_KIND VARCHAR(20) NOT NULL,
  LAST_VALUES_JSON VARCHAR(18000),
  CONSTRAINT PK_SOURCE_ITEMS PRIMARY KEY (WORKSPACE_ID,SOURCE_ID,EXTERNAL_ID) ENABLE,
  CONSTRAINT FK_SOURCE_ITEM_SOURCE FOREIGN KEY (WORKSPACE_ID,SOURCE_ID) REFERENCES CONNECTED_SOURCES(WORKSPACE_ID,ID) ENABLE
);
