-- Local OSS OAuth: browser state and plan credentials are encrypted at rest.
CREATE TABLE OPENAI_OAUTH_TRANSACTIONS (
  BROWSER_HASH VARCHAR(64) NOT NULL,
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  USER_ID VARCHAR(36) NOT NULL,
  SESSION_HASH VARCHAR(64) NOT NULL,
  PAYLOAD VARCHAR(8000) NOT NULL,
  EXPIRES_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_OPENAI_OAUTH_TRANSACTIONS PRIMARY KEY (BROWSER_HASH) ENABLE,
  CONSTRAINT FK_OPENAI_OAUTH_OWNER FOREIGN KEY (WORKSPACE_ID,USER_ID) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
CREATE TABLE OPENAI_CONNECTIONS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  USER_ID VARCHAR(36) NOT NULL,
  HOST_ID VARCHAR(100) NOT NULL,
  CLIENT_ID VARCHAR(220) NOT NULL,
  ISSUER VARCHAR(200) NOT NULL,
  SUBJECT VARCHAR(512) NOT NULL,
  EMAIL VARCHAR(320),
  DISPLAY_NAME VARCHAR(160),
  VERIFIED_AT TIMESTAMP NOT NULL,
  CREDENTIALS VARCHAR(200000),
  SCOPES VARCHAR(2000) NOT NULL,
  ACTIVE BOOLEAN NOT NULL,
  AUTH_VERSION DECIMAL(18,0) NOT NULL,
  MODEL VARCHAR(200),
  REFRESH_OWNER VARCHAR(36),
  REFRESH_UNTIL TIMESTAMP,
  CONSTRAINT PK_OPENAI_CONNECTIONS PRIMARY KEY (WORKSPACE_ID,USER_ID,HOST_ID,CLIENT_ID) ENABLE,
  CONSTRAINT FK_OPENAI_CONNECTION_OWNER FOREIGN KEY (WORKSPACE_ID,USER_ID) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
