CREATE TABLE WORKSPACE_SETTINGS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  VERSION DECIMAL(18,0) NOT NULL,
  SETTINGS_JSON VARCHAR(220000) NOT NULL,
  UPDATED_BY VARCHAR(36) NOT NULL,
  UPDATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_WORKSPACE_SETTINGS PRIMARY KEY (WORKSPACE_ID) ENABLE,
  CONSTRAINT FK_SETTINGS_WORKSPACE FOREIGN KEY (WORKSPACE_ID) REFERENCES WORKSPACES(ID) ENABLE,
  CONSTRAINT FK_SETTINGS_AUTHOR FOREIGN KEY (WORKSPACE_ID,UPDATED_BY) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
CREATE TABLE AGENT_CONNECTIONS (
  ID VARCHAR(36) NOT NULL,
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  VERSION DECIMAL(18,0) NOT NULL,
  LABEL VARCHAR(100) NOT NULL,
  CLIENT VARCHAR(20) NOT NULL,
  CREATED_BY VARCHAR(36) NOT NULL,
  TOKEN_HASH VARCHAR(64) NOT NULL,
  TOKEN_PREFIX VARCHAR(24) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  EXPIRES_AT TIMESTAMP NOT NULL,
  REVOKED_AT TIMESTAMP,
  LAST_USED_AT TIMESTAMP,
  CLIENT_NAME VARCHAR(100),
  CONSTRAINT PK_AGENT_CONNECTIONS PRIMARY KEY (ID) ENABLE,
  CONSTRAINT FK_AGENT_WORKSPACE FOREIGN KEY (WORKSPACE_ID) REFERENCES WORKSPACES(ID) ENABLE,
  CONSTRAINT FK_AGENT_CREATOR FOREIGN KEY (WORKSPACE_ID,CREATED_BY) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
