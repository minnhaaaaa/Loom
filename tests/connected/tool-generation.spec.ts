import { expect, test } from "@playwright/test";
import {
  personas,
  type PublishedTool,
  type ToolDraft,
  type ToolWorkspace,
  type ToolSpec,
} from "../../packages/contracts/src/index";

const origin = "http://127.0.0.1:3200";

test("a live model generates a persisted draft that an owner reviews and publishes for requesters", async ({
  page,
  request,
}, testInfo) => {
  test.skip(
    process.env.LOOM_TEST_LIVE_TOOL_GENERATION !== "true" ||
      !process.env.OPENROUTER_API_KEY ||
      !(process.env.OPENROUTER_TOOL_MODEL || process.env.OPENROUTER_MODEL),
    "Live tool generation requires explicit opt-in and configured OpenRouter credentials; this journey uses the real provider.",
  );
  test.setTimeout(210_000);

  const signedIn = await request.post("/api/session", {
    headers: { Origin: origin },
    data: { userId: personas[0].id },
  });
  expect(signedIn.ok()).toBe(true);
  const workspaceResponse = await request.get("/api/tool");
  expect(workspaceResponse.ok()).toBe(true);
  const initial = (await workspaceResponse.json()) as ToolWorkspace;
  expect(initial.configuration.configured).toBe(true);
  const original = initial.published;
  const title = `Live AI desk ${crypto.randomUUID().slice(0, 8)}`;
  const instructions = [
    `Change ONLY the tool title to exactly "${title}".`,
    "Preserve every other setting from the current specification exactly: description; field IDs, labels, types, visibility, requiredness, and length limits; field order; queue columns and order; filters; summary metrics; actions and order; and status labels.",
    "Do not add or remove fields, including custom fields. Do not change any request records.",
    "Include one assumption explaining that all workflow settings remain unchanged. There are no unsupported requirements, so return an empty unsupported array.",
  ].join(" ");

  try {
    await page.goto("/app?view=settings");
    await page
      .getByRole("combobox", { name: "Demo persona" })
      .selectOption(personas[0].id);
    const builder = page.locator(".tool-builder");
    await builder.getByText("Customize this desk", { exact: true }).click();
    await builder
      .getByLabel("Describe your tool or the changes you want", { exact: true })
      .fill(instructions);
    const generate = builder.getByRole("button", {
      name: "Generate a draft",
      exact: true,
    });
    await expect(generate).toBeEnabled();
    const generationResponse = page.waitForResponse(
      (response) =>
        new URL(response.url()).pathname === "/api/tool/generate" &&
        response.request().method() === "POST",
      { timeout: 110_000 },
    );
    await generate.click();
    const generated = await generationResponse;
    const body = await generated.json();
    expect(generated.ok(), JSON.stringify(body.error ?? {})).toBe(true);
    const draft = body as ToolDraft;
    const inference = draft.inference;
    await testInfo.attach("live-tool-generation.json", {
      body: JSON.stringify(
        {
          draftId: draft.id,
          baseRevision: draft.baseRevision,
          requestedModel: initial.configuration.model,
          actualModel: inference?.actualModel ?? null,
          generationId: inference?.generationId ?? null,
          cost: inference?.cost ?? null,
          inferenceAvailable: Boolean(inference),
        },
        null,
        2,
      ),
      contentType: "application/json",
    });
    expect(draft.baseRevision).toBe(original.revision);
    expect(draft.hash).toMatch(/^[a-f0-9]{64}$/);
    expect(inference?.actualModel).toBeTruthy();
    expect(inference?.requestedModel).toBe(initial.configuration.model);
    expect(inference?.generationId).toBeTruthy();
    expect(draft.spec).toEqual({ ...original.spec, title });
    expect(draft.assumptions.length).toBeGreaterThan(0);
    expect(draft.unsupported).toEqual([]);

    const pendingResponse = await request.get("/api/tool");
    expect(pendingResponse.ok()).toBe(true);
    const pending = (await pendingResponse.json()) as ToolWorkspace;
    expect(pending.published).toEqual(original);
    expect(pending.drafts.find((saved) => saved.id === draft.id)).toMatchObject(
      {
        hash: draft.hash,
        spec: draft.spec,
        assumptions: draft.assumptions,
        unsupported: [],
      },
    );
    await expect(page.locator(".current-tool-label")).toContainText(
      original.spec.title,
    );
    await expect(
      builder.getByRole("heading", { name: title, exact: true }),
    ).toBeVisible();
    await expect(
      builder.getByRole("heading", { name: "Model assumptions", exact: true }),
    ).toBeVisible();
    await expect(
      builder.getByRole("heading", {
        name: `Generated by ${inference?.actualModel}`,
        exact: true,
      }),
    ).toBeVisible();
    if (inference?.cost !== null && inference?.cost !== undefined)
      await expect(
        builder.getByText(`Reported cost: ${inference.cost} USD`, {
          exact: false,
        }),
      ).toBeVisible();
    for (const assumption of draft.assumptions)
      await expect(
        builder.getByText(assumption, { exact: true }),
      ).toBeVisible();
    await expect(
      builder.getByRole("button", {
        name: "Publish reviewed tool",
        exact: true,
      }),
    ).toBeDisabled();

    // Load the durable draft after a fresh page load before reviewing its hash.
    await page.reload();
    await builder.getByText("Customize this desk", { exact: true }).click();
    await builder
      .getByText("Saved drafts and publication history", { exact: true })
      .click();
    await builder
      .locator(".tool-builder-history-grid article")
      .filter({ hasText: title })
      .getByRole("button", { name: "Review saved draft", exact: true })
      .click();
    const review = builder.getByRole("checkbox", {
      name: "I reviewed this saved draft and its exact changes.",
      exact: true,
    });
    await expect(review).not.toBeChecked();
    await expect(
      builder.getByRole("heading", {
        name: `Generated by ${inference?.actualModel}`,
        exact: true,
      }),
    ).toBeVisible();
    await expect(page.locator(".current-tool-label")).toContainText(
      original.spec.title,
    );
    await review.check();
    const publicationResponse = page.waitForResponse(
      (response) =>
        new URL(response.url()).pathname === "/api/tool/publish" &&
        response.request().method() === "POST",
    );
    await builder
      .getByRole("button", { name: "Publish reviewed tool", exact: true })
      .click();
    const publication = await publicationResponse;
    expect(publication.ok()).toBe(true);
    const published = (await publication.json()) as PublishedTool;
    expect(published.revision).toBe(original.revision + 1);
    expect(published.spec).toEqual(draft.spec);
    await expect(page.locator(".current-tool-label")).toContainText(title);

    await page
      .getByRole("combobox", { name: "Demo persona" })
      .selectOption(personas[2].id);
    await expect(builder).toHaveCount(0);
    await page.goto("/app?view=records");
    await expect(page.getByRole("heading", { level: 1 })).toHaveText(title);
    await page.reload();
    await expect(page.getByRole("heading", { level: 1 })).toHaveText(title);
    await page.screenshot({
      path: "test-results/live-tool-generation.png",
      fullPage: true,
    });
  } finally {
    // Restore through the same draft/publication API; request records are untouched.
    const ownerSession = await request.post("/api/session", {
      headers: { Origin: origin },
      data: { userId: personas[0].id },
    });
    expect(ownerSession.ok()).toBe(true);
    const currentResponse = await request.get("/api/tool");
    expect(currentResponse.ok()).toBe(true);
    const current = ((await currentResponse.json()) as ToolWorkspace).published;
    if (JSON.stringify(current.spec) !== JSON.stringify(original.spec)) {
      const restoredDraftResponse = await request.post("/api/tool/drafts", {
        headers: { Origin: origin },
        data: {
          commandId: crypto.randomUUID(),
          expectedRevision: current.revision,
          spec: original.spec,
          instructions:
            "Restore the definition used before the synthetic live-model browser check.",
        },
      });
      expect(restoredDraftResponse.ok()).toBe(true);
      const restoredDraft = (await restoredDraftResponse.json()) as ToolDraft;
      const restoredResponse = await request.post("/api/tool/publish", {
        headers: { Origin: origin },
        data: {
          commandId: crypto.randomUUID(),
          draftId: restoredDraft.id,
          expectedRevision: current.revision,
          hash: restoredDraft.hash,
        },
      });
      expect(restoredResponse.ok()).toBe(true);
      expect(((await restoredResponse.json()) as PublishedTool).spec).toEqual(
        original.spec,
      );
    }
  }
});

test("browser-only failure fixtures preserve a draft and require explicit rate-limit and exhausted-generation retries", async ({
  page,
  request,
}) => {
  await request.post("/api/session", {
    headers: { Origin: origin },
    data: { userId: personas[0].id },
  });
  const initialResponse = await request.get("/api/tool");
  expect(initialResponse.ok()).toBe(true);
  const initial = (await initialResponse.json()) as ToolWorkspace;
  const attempts: {
    commandId: string;
    instructions: string;
    baseSpec: ToolSpec;
  }[] = [];
  // These fixtures exercise browser recovery only. No provider or publication is called.
  await page.route("**/api/tool", async (route) => {
    await route.fulfill({
      status: 200,
      contentType: "application/json",
      body: JSON.stringify({
        ...initial,
        configuration: {
          configured: true,
          model: "browser-fixture/designer",
          message: "Browser-only failure fixture; no live provider call.",
        },
      }),
    });
  });
  await page.route("**/api/tool/generate", async (route) => {
    attempts.push(route.request().postDataJSON());
    const failure =
      attempts.length === 1
        ? {
            status: 429,
            error: {
              code: "MODEL_HTTP_429",
              message: "Synthetic rate limit. Retry after the displayed wait.",
              retryAfterSeconds: 2,
              retryable: true,
            },
          }
        : attempts.length === 2
          ? {
              status: 409,
              error: {
                code: "GENERATION_RETRY_LIMIT",
                message: "Synthetic generation has used its two attempts.",
                retryable: false,
              },
            }
          : attempts.length === 3
            ? {
                status: 503,
                error: {
                  code: "MODEL_NETWORK",
                  message:
                    "Synthetic provider interruption. Your draft is preserved.",
                  retryable: true,
                },
              }
            : {
                status: 503,
                error: {
                  code: "MODEL_HTTP_401",
                  message:
                    "Synthetic provider authentication failure. Refresh model settings before retrying.",
                  retryable: false,
                },
              };
    await route.fulfill({
      status: failure.status,
      contentType: "application/json",
      headers: failure.status === 429 ? { "Retry-After": "2" } : {},
      body: JSON.stringify({ error: failure.error }),
    });
  });

  await page.goto("/app?view=settings");
  await page
    .getByRole("combobox", { name: "Demo persona" })
    .selectOption(personas[0].id);
  const builder = page.locator(".tool-builder");
  await builder.getByText("Customize this desk", { exact: true }).click();
  const instructions = "Change only the title of this synthetic draft.";
  const description = builder.getByRole("textbox", {
    name: "Describe your tool or the changes you want",
    exact: true,
  });
  await description.fill(instructions);
  await builder
    .getByLabel("Tool title", { exact: true })
    .fill("Synthetic retry draft");
  await builder
    .getByRole("button", { name: "Generate a draft", exact: true })
    .click();
  await expect(
    builder.getByRole("alert").filter({ hasText: "Synthetic rate limit." }),
  ).toBeVisible();
  const retry = builder.getByRole("button", {
    name: "Retry generation",
    exact: true,
  });
  await expect(retry).toBeDisabled();
  await expect(description).toHaveValue(instructions);
  await expect(builder.getByLabel("Tool title", { exact: true })).toHaveValue(
    "Synthetic retry draft",
  );
  await expect(retry).toBeEnabled({ timeout: 6000 });
  expect(attempts).toHaveLength(1);
  await retry.click();
  const fresh = builder.getByRole("button", {
    name: "Start new generation",
    exact: true,
  });
  await expect(fresh).toBeEnabled();
  await expect(retry).toBeDisabled();
  expect(attempts).toHaveLength(2);
  expect(attempts[1].commandId).toBe(attempts[0].commandId);
  expect(attempts[1].baseSpec).toEqual(attempts[0].baseSpec);
  await fresh.click();
  await expect(
    builder
      .getByRole("alert")
      .filter({ hasText: "Synthetic provider interruption." }),
  ).toBeVisible();
  expect(attempts).toHaveLength(3);
  expect(attempts[2].commandId).not.toBe(attempts[0].commandId);
  expect(attempts[2].instructions).toBe(instructions);
  expect(attempts[2].baseSpec).toEqual(attempts[0].baseSpec);
  await retry.click();
  await expect(
    builder
      .getByRole("alert")
      .filter({ hasText: "Synthetic provider authentication failure." }),
  ).toBeVisible();
  await expect(retry).toBeDisabled();
  expect(attempts).toHaveLength(4);
  expect(attempts[3].commandId).toBe(attempts[2].commandId);
  await builder
    .getByRole("button", { name: "Refresh model availability", exact: true })
    .click();
  await expect(
    builder.getByRole("button", { name: "Generate a draft", exact: true }),
  ).toBeEnabled();
  await expect(
    builder
      .getByRole("alert")
      .filter({ hasText: "Synthetic provider authentication failure." }),
  ).toHaveCount(0);
  expect(attempts).toHaveLength(4);
  await expect(description).toHaveValue(instructions);
  await expect(builder.getByLabel("Tool title", { exact: true })).toHaveValue(
    "Synthetic retry draft",
  );
  await expect(page.locator(".current-tool-label")).toContainText(
    initial.published.spec.title,
  );
  const unchangedResponse = await request.get("/api/tool");
  expect(unchangedResponse.ok()).toBe(true);
  expect(((await unchangedResponse.json()) as ToolWorkspace).published).toEqual(
    initial.published,
  );
});
