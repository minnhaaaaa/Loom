CREATE TABLE KNOWLEDGE_ENTRIES (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  ID VARCHAR(36) NOT NULL,
  VERSION DECIMAL(18,0) NOT NULL,
  LIFECYCLE VARCHAR(20) NOT NULL,
  KIND VARCHAR(20) NOT NULL,
  DATASET VARCHAR(200),
  CONTENT_JSON VARCHAR(20000) NOT NULL,
  CONTENT_HASH VARCHAR(64) NOT NULL,
  CREATED_BY VARCHAR(36) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  APPROVED_BY VARCHAR(36),
  CONSTRAINT PK_KNOWLEDGE PRIMARY KEY (WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_KNOWLEDGE_CREATOR FOREIGN KEY (WORKSPACE_ID,CREATED_BY) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE,
  CONSTRAINT FK_KNOWLEDGE_APPROVER FOREIGN KEY (WORKSPACE_ID,APPROVED_BY) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
CREATE TABLE AGENT_RUNS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  ID VARCHAR(36) NOT NULL,
  INITIATOR_ID VARCHAR(36) NOT NULL,
  REQUEST_IDS_JSON VARCHAR(1000) NOT NULL,
  STATUS VARCHAR(20) NOT NULL,
  VERSION DECIMAL(18,0) NOT NULL,
  CHECKPOINT DECIMAL(18,0) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  EXPIRES_AT TIMESTAMP NOT NULL,
  ENGINE VARCHAR(20) NOT NULL,
  TOOL_REVISION VARCHAR(40) NOT NULL,
  CONSTRAINT PK_AGENT_RUNS PRIMARY KEY (WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_RUN_INITIATOR FOREIGN KEY (WORKSPACE_ID,INITIATOR_ID) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
CREATE TABLE TRIAGE_PROPOSALS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  ID VARCHAR(36) NOT NULL,
  RUN_ID VARCHAR(36) NOT NULL,
  REQUEST_ID VARCHAR(36) NOT NULL,
  CONTENT_JSON VARCHAR(150000) NOT NULL,
  CONTENT_HASH VARCHAR(64) NOT NULL,
  LIFECYCLE VARCHAR(20) NOT NULL,
  REVIEWED_BY VARCHAR(36),
  CONSTRAINT PK_TRIAGE_PROPOSALS PRIMARY KEY (WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_PROPOSAL_RUN FOREIGN KEY (WORKSPACE_ID,RUN_ID) REFERENCES AGENT_RUNS(WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_PROPOSAL_REQUEST FOREIGN KEY (WORKSPACE_ID,REQUEST_ID) REFERENCES REQUESTS(WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_PROPOSAL_REVIEWER FOREIGN KEY (WORKSPACE_ID,REVIEWED_BY) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
CREATE TABLE AGENT_STEPS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  RUN_ID VARCHAR(36) NOT NULL,
  STEP_INDEX DECIMAL(18,0) NOT NULL,
  REQUEST_ID VARCHAR(36) NOT NULL,
  REQUEST_VERSION DECIMAL(18,0) NOT NULL,
  OUTPUT_JSON VARCHAR(10000) NOT NULL,
  PROPOSAL_ID VARCHAR(36),
  CONSTRAINT PK_AGENT_STEPS PRIMARY KEY (WORKSPACE_ID,RUN_ID,STEP_INDEX) ENABLE,
  CONSTRAINT FK_STEP_RUN FOREIGN KEY (WORKSPACE_ID,RUN_ID) REFERENCES AGENT_RUNS(WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_STEP_REQUEST FOREIGN KEY (WORKSPACE_ID,REQUEST_ID) REFERENCES REQUESTS(WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_STEP_PROPOSAL FOREIGN KEY (WORKSPACE_ID,PROPOSAL_ID) REFERENCES TRIAGE_PROPOSALS(WORKSPACE_ID,ID) ENABLE
);
CREATE TABLE AGENT_EVENTS (
  WORKSPACE_ID VARCHAR(36) NOT NULL,
  ID VARCHAR(36) NOT NULL,
  RESOURCE_ID VARCHAR(36) NOT NULL,
  ACTOR_ID VARCHAR(36) NOT NULL,
  ACTION_KIND VARCHAR(40) NOT NULL,
  VERSION DECIMAL(18,0) NOT NULL,
  CREATED_AT TIMESTAMP NOT NULL,
  CONSTRAINT PK_AGENT_EVENTS PRIMARY KEY (WORKSPACE_ID,ID) ENABLE,
  CONSTRAINT FK_AGENT_EVENT_ACTOR FOREIGN KEY (WORKSPACE_ID,ACTOR_ID) REFERENCES MEMBERSHIPS(WORKSPACE_ID,USER_ID) ENABLE
);
