import { randomUUID } from "node:crypto";
import { afterAll, beforeAll, expect, it } from "vitest";
import { isConfigured, readDatabase, writeDatabase } from "@loom/db-exasol";
import {
  createRequest,
  details,
  mutateRequest,
  snapshot,
} from "../../apps/web/server/desk";
import type { Actor } from "@loom/contracts";
if (!isConfigured())
  throw new Error(
    "Live Exasol is required. Configure .env and run db:migrate before test:db. This suite never substitutes a fake database.",
  );
const workspaceA = randomUUID(),
  workspaceB = randomUUID();
const owner: Actor = { workspaceId: workspaceA, userId: randomUUID() };
const requester: Actor = { workspaceId: workspaceA, userId: randomUUID() };
const other: Actor = { workspaceId: workspaceB, userId: requester.userId };
const viewer: Actor = { workspaceId: workspaceA, userId: randomUUID() };
beforeAll(async () => {
  await writeDatabase(async (sql) => {
    for (const id of [workspaceA, workspaceB])
      await sql.execute("INSERT INTO WORKSPACES (ID,NAME) VALUES (?,?)", [
        id,
        "Loom integration fixture",
      ]);
    for (const [actor, name, role] of [
      [owner, "Fixture owner", "owner"],
      [requester, "Fixture requester", "requester"],
      [other, "Other requester", "requester"],
      [viewer, "Fixture viewer", "viewer"],
    ] as const)
      await sql.execute(
        "INSERT INTO MEMBERSHIPS (WORKSPACE_ID,USER_ID,NAME,ROLE,ACTIVE) VALUES (?,?,?,?,TRUE)",
        [actor.workspaceId, actor.userId, name, role],
      );
  });
});
afterAll(async () => {
  // Only UUIDs generated by this invocation are deleted. Never reset user data.
  await writeDatabase(async (sql) => {
    for (const table of [
      "COMMENTS",
      "REQUEST_EVENTS",
      "AUDIT_EVENTS",
      "OUTBOX_EVENTS",
      "COMMAND_RECEIPTS",
      "REQUESTS",
      "MEMBERSHIPS",
      "WORKSPACES",
    ]) {
      for (const id of [workspaceA, workspaceB])
        await sql.execute(
          `DELETE FROM ${table} WHERE ${table === "WORKSPACES" ? "ID" : "WORKSPACE_ID"} = ?`,
          [id],
        );
    }
  });
});
it("persists commands atomically, isolates readers, and rejects stale/replayed conflicts", async () => {
  const commandId = randomUUID();
  const values = {
    title: "Live integration fixture",
    businessQuestion: "Verify the real SQL path.",
    reportingPeriod: "October 2026",
    dataset: "Synthetic events",
  };
  const record = await createRequest(requester, commandId, values);
  expect((await createRequest(requester, commandId, values)).id).toBe(
    record.id,
  );
  await expect(
    createRequest(requester, commandId, {
      ...values,
      title: "Changed payload",
    }),
  ).rejects.toThrow("different action");
  await createRequest(owner, randomUUID(), {
    ...values,
    title: "Owner-only request",
  });
  expect((await snapshot(requester)).requests).toHaveLength(1);
  expect((await snapshot(other)).requests).toHaveLength(0);
  await expect(details(other, record.id)).rejects.toThrow("not found");
  await expect(
    mutateRequest(viewer, record.id, randomUUID(), 1, {
      type: "set_status",
      status: "ready",
    }),
  ).rejects.toThrow("Viewers cannot");
  const comment = await mutateRequest(owner, record.id, randomUUID(), 1, {
    type: "add_comment",
    body: "Internal fixture note",
    visibility: "internal",
  });
  expect(comment.version).toBe(2);
  expect((await details(requester, record.id)).comments).toHaveLength(0);
  expect((await details(owner, record.id)).comments).toHaveLength(1);
  const results = await Promise.allSettled([
    mutateRequest(owner, record.id, randomUUID(), 2, {
      type: "set_status",
      status: "ready",
    }),
    mutateRequest(owner, record.id, randomUUID(), 2, {
      type: "set_priority",
      priority: "high",
    }),
  ]);
  expect(results.filter((r) => r.status === "fulfilled")).toHaveLength(1);
  expect(results.filter((r) => r.status === "rejected")).toHaveLength(1);
  await expect(
    mutateRequest(owner, record.id, randomUUID(), 1, {
      type: "set_priority",
      priority: "low",
    }),
  ).rejects.toThrow("changed");
  await readDatabase(async (sql) => {
    const [r] = await sql.query(
      "SELECT COUNT(*) AS N FROM COMMAND_RECEIPTS WHERE WORKSPACE_ID = ?",
      [workspaceA],
    );
    expect(Number(r.N)).toBe(4); // two creates, comment, one winning concurrent command
    const [events] = await sql.query(
      "SELECT COUNT(*) AS N FROM AUDIT_EVENTS WHERE WORKSPACE_ID = ?",
      [workspaceA],
    );
    expect(Number(events.N)).toBe(4);
  });
});
it("rolls back a partial write instead of leaving an unacknowledged record", async () => {
  const id = randomUUID();
  await expect(
    writeDatabase(async (sql) => {
      await sql.execute("INSERT INTO WORKSPACES (ID,NAME) VALUES (?,?)", [
        id,
        "Rollback fixture",
      ]);
      throw new Error("intentional rollback");
    }),
  ).rejects.toThrow("intentional rollback");
  const rows = await readDatabase((sql) =>
    sql.query("SELECT ID FROM WORKSPACES WHERE ID = ?", [id]),
  );
  expect(rows).toEqual([]);
});
